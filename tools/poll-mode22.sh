#!/bin/bash
# スキャンで見つかった Mode 22 有効PID を連続ポーリングし、
# 標準PID（水温・吸気温・MAF・MAP）と並べて記録する。
#
# 使い方:  sudo bash poll-mode22.sh <scan-mode22.sh のログ> [記録先]
#
# 【重要】温度らしい値を見つけても、それが「独立した温度」か
# 「他の温度から導かれた値」かを必ず切り分けること。2回続けて誤った。
#
#   0x114A → 吸気温の派生値だった (#123 で ATF油温と誤認)
#   0x114D → 水温センサーの生値だった (2026-08-27 に ATF油温と誤認)
#
# ■ 相関の高さは何の証拠にもならない
# 0x114D と水温の相関は -0.996 だった。しかし派生値なのだから当然である。
# 車の温度はどれも一緒に上がるので、独立した温度どうしでも相関は高く出る。
#
# ■ ラグも当てにならない
# 「熱容量があれば応答が遅れる」という理屈でラグを見たが、暖機中のデータは
# どちらも滑らかな単調曲線なので、どのラグでも相関が 0.94〜0.997 と高く、
# ピークが平坦で判定にならなかった。実際 0x114D のピークは lag -20秒 で
# r=-0.9969、lag 0 でも -0.9959 と、差が 0.001 しかなかった。
#
# ■ 効く判定: 同じ基準温度で、条件を正反対にして比べる
# 派生値なら「基準の温度が同じなら値も同じ」になる。独立した温度なら
# 発熱条件が違えば値も違う。ATF なら停車アイドルと高速走行でトルコンの
# 発熱が桁違いなので、水温が同じでも油温は大きく変わるはずである。
#
#   1. 候補PIDと水温・吸気温を、走行条件を変えて何度も記録する
#   2. サンプルごとの「瞬間車速」を必ず記録する
#      ログ全体の最高速で分類してはいけない。87℃のサンプルが走行前の
#      アイドリング中だったなら、条件を変えた比較になっていない
#   3. 同じ水温のサンプルを、停車中 (<5km/h) と走行中 (>40km/h) に分けて
#      値を比べる
#        値が一致する   → 派生値。独立した温度ではない
#        値が有意に違う → 独立した温度の可能性が高い
#
# 0x114D は水温87℃のとき停車中 37.49、走行中 37.38 で一致した。
# 6つの水温すべてで差は分解能 (0.25) 以下だった。
#
set -u
IF=${IF:-can0}
SCANLOG=${1:?scan-mode22.sh のログを指定してください}
OUT=${2:-/tmp/poll22_$(date +%Y%m%d_%H%M%S).log}

PIDS=$(awk '$6=="62"{print $7 $8}' "$SCANLOG" | sort -u | tr '\n' ' ')
[ -z "$PIDS" ] && { echo "有効PIDが見つからない: $SCANLOG"; exit 1; }
echo "対象PID: $(echo "$PIDS" | wc -w) 個"
echo "記録先 : $OUT"

candump -ta "$IF" > "$OUT" 2>/dev/null &
CD=$!
trap 'kill $CD 2>/dev/null' EXIT

while true; do
  for P in $PIDS; do
    cansend "$IF" 7E0#0322${P}00000000 2>/dev/null
    sleep 0.03
  done
  # 対照群: 水温 / 吸気温 / MAF / MAP
  for P in 05 0F 10 0B; do
    cansend "$IF" 7DF#0201${P}0000000000 2>/dev/null
    sleep 0.03
  done
done
